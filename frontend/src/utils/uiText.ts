const escapeRegExp = (value: string) => value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

export const translateUiText = (value?: string | null) => {
  if (!value) {
    return value || "";
  }

  if (exactTranslations[value]) {
    return exactTranslations[value];
  }

  let translated = value;

  for (const [source, target] of partialTranslations.sort((a, b) => b[0].length - a[0].length)) {
    translated = translated.replace(new RegExp(escapeRegExp(source), "g"), target);
  }

  return translated;
};

